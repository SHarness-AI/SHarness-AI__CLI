"""Where the door sends: the Store a target implements. Paths are relative to the root, already
normalised by the door; a store that cannot keep a path inside its root raises OutsideRoot."""


class OutsideRoot(Exception):
    pass


class Store:
    mode = "live"                                   # or "twin"

    def exists(self, rel: str) -> bool: ...
    def read(self, rel: str) -> bytes: ...
    def write(self, rel: str, data: bytes) -> None: ...
    def append(self, rel: str, data: bytes) -> None: ...
    def delete(self, rel: str) -> None: ...
    def mkdir(self, rel: str) -> None: ...
    def listing(self) -> list: ...
